/** The parts of one lesson, in order, that actually exist on disk.
 *  Derived from VIDEOS rather than listed by hand — the number of parts depends
 *  on how the narration packed, and a hand-kept list would drift the first time
 *  a lesson is re-cut. */
export const lessonParts = (n) =>
  [...VIDEOS].filter((id) => new RegExp(`^lesson-${n}[a-j]$`).test(id)).sort();
